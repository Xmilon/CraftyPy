def load_worker():
    spec = importlib.util.spec_from_file_location("craftpy_worker_docs", WORKER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def resolve(worker, key):
    names = worker._api_names()
    owner, _, member = key.partition(".")
    obj = names[owner]
    if not member:
        return obj
    return getattr(obj if inspect.isclass(obj) else type(obj), member)


def signature_of(target, drop_self):
    sig = inspect.signature(target)
    params = [p for p in sig.parameters.values() if not (drop_self and p.name in ("self", "cls"))]
    return sig.replace(parameters=params)


def build(worker=None):
    """Returns (markdown, missing) where missing lists 'key: parameter' pairs without a description."""
    worker = worker or load_worker()
    docs = worker._DOCS
    missing = []
    out = [START, ""] + versions(worker) + ["## Reference", "",
           "Every function, class and method with all its parameters, by topic. Use the search of this page, or hover a "
           "name in the editor (`Ctrl+Q`).", ""]
    for chapter, keys in CHAPTERS:
        out += ["### " + chapter, ""]
        for key in keys:
            if key not in docs:
                missing.append("%s: no documentation" % key)
                continue
            summary, params, returns = docs[key]
            target = resolve(worker, key)
            owner, _, member = key.partition(".")
            drop_self = bool(member)  # methods of classes and of API objects like world
            try:
                sig = signature_of(target, drop_self)
            except (TypeError, ValueError):
                sig = None
            shown = key if member else key
            out += ["#### `%s%s`" % (shown, sig if sig is not None else "()"), "", summary, ""]
            if key in worker._DEPRECATED:
                since, use = worker._DEPRECATED[key]
                out += ["Old API (replaced in %s, still works): use %s." % (since, use), ""]
            rows = []
            if sig is not None:
                for p in sig.parameters.values():
                    prefix = "*" if p.kind is p.VAR_POSITIONAL else "**" if p.kind is p.VAR_KEYWORD else ""
                    default = "" if p.default is p.empty else "`%r`" % (p.default,)
                    text = params.get(p.name) or GENERIC.get(p.name, "")
                    if not text:
                        missing.append("%s: %s" % (key, p.name))
                    rows.append((prefix + p.name, default, text))
            if rows:
                out += ["| Parameter | Default | Meaning |", "| --- | --- | --- |"]
                out += ["| `%s` | %s | %s |" % (name, default, text.replace("|", "\\|")) for name, default, text in rows]
                out.append("")
            if returns:
                out += ["Returns: " + returns, ""]
    out.append(END)
    return "\n".join(out) + "\n", missing


def versions(worker):
    """The "API versions" part: the rules, the current version and what each version changed."""
    out = ["## API versions", "",
           "This page describes Python API **%s** (`API_VERSION` in your code). `apiVersion` in `project.json` says which "
           "version a project was written for." % worker.API_VERSION, "",
           "- A **minor** version (2.0 to 2.1) only adds things: everything written for 2.0 keeps working.",
           "- A **major** version (1 to 2) may rename things. The old names keep working; after a run the console "
           "says `[api] ... is the old API` and what to write instead.",
           "- A project written for a newer API than your CraftPy gets a note to update CraftPy.", ""]
    labels = [("added", "Added"), ("changed", "Changed"), ("deprecated", "Old names (still work)"), ("removed", "Removed")]
    for change in worker.API_CHANGES:
        title = "### " + change["version"] + (" (" + change["date"] + ")" if change.get("date") else "")
        out += [title, ""]
        for key, label in labels:
            for line in change.get(key, []):
                out.append("- **%s:** %s" % (label, line))
        out.append("")
    return out


def current_text():
    with open(API_MD, encoding="utf-8") as handle:
        return handle.read()


def merged(text, generated):
    if START in text:
        text = text[:text.index(START)].rstrip() + "\n\n"
    else:
        text = text.rstrip() + "\n\n"
    return text + generated


if __name__ == "__main__":
    generated, missing = build()
    if missing:
        raise SystemExit("undocumented:\n  " + "\n  ".join(missing))
    text = merged(current_text(), generated)  # read before the file is opened for writing
    with open(API_MD, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("api.md updated")
