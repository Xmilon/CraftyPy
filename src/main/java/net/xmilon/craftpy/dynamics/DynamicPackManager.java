package net.xmilon.craftpy.dynamics;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Optional;

import net.minecraft.network.chat.Component;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackSelectionConfig;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.PathPackResources;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.neoforged.neoforge.event.AddPackFindersEvent;

/**
 * Registers the generated dynamic pack folders with the resource (client) and
 * data (server) repositories, and offers reload triggers. The folder contents
 * are regenerated by {@link PackBuilder}; repository sources re-read them on
 * every reload, so no restart is needed after a project load/unload.
 */
public final class DynamicPackManager {
    public static final String PACK_ID = "craftpy:dynamic";

    private DynamicPackManager() {
    }

    public static void registerSources(AddPackFindersEvent event) {
        PackType type = event.getPackType();
        Path root = type == PackType.CLIENT_RESOURCES ? PackBuilder.resourcePackRoot() : PackBuilder.dataPackRoot();
        // Always register the source; the folder may only appear later (after a
        // project load). The repository re-runs sources on every reload, so the
        // pack becomes available without a restart once PackBuilder has written it.
        event.addRepositorySource(consumer -> {
            if (root == null || !Files.isDirectory(root)) {
                return;
            }
            if (type == PackType.CLIENT_RESOURCES && net.xmilon.craftpy.client.ServerPack.active()) {
                return; // on a server of another computer its pack (below) replaces the one of your own projects
            }
            Pack pack = Pack.readMetaAndCreate(
                    new PackLocationInfo(PACK_ID, Component.literal("CraftPy Projects"),
                            PackSource.BUILT_IN, Optional.empty()),
                    new PathPackResources.PathResourcesSupplier(root),
                    type,
                    // required=never user-toggleable, always selected so slot
                    // blockstates/models resolve at startup without a manual reload.
                    new PackSelectionConfig(true, Pack.Position.TOP, false));
            if (pack != null) {
                consumer.accept(pack);
            }
        });
        if (type == PackType.CLIENT_RESOURCES) {
            // the server you joined from this computer: its projects' and modules' resources (ServerPack)
            event.addRepositorySource(consumer -> {
                if (!net.xmilon.craftpy.client.ServerPack.active()) {
                    return;
                }
                Pack pack = Pack.readMetaAndCreate(
                        new PackLocationInfo("craftpy:server", Component.literal("CraftPy: this server"),
                                PackSource.SERVER, Optional.empty()),
                        new PathPackResources.PathResourcesSupplier(net.xmilon.craftpy.client.ServerPack.root()),
                        type,
                        new PackSelectionConfig(true, Pack.Position.TOP, false));
                if (pack != null) {
                    consumer.accept(pack);
                }
            });
            // client-side modules: this computer's own pack, on any server (rebuilt here when the modules changed)
            event.addRepositorySource(consumer -> {
                ClientModulePack.refresh();
                Path modules = ClientModulePack.root();
                if (!Files.isDirectory(modules)) {
                    return;
                }
                Pack pack = Pack.readMetaAndCreate(
                        new PackLocationInfo(ClientModulePack.PACK_ID, Component.literal("CraftPy client modules"),
                                PackSource.BUILT_IN, Optional.empty()),
                        new PathPackResources.PathResourcesSupplier(modules),
                        type,
                        new PackSelectionConfig(true, Pack.Position.TOP, false));
                if (pack != null) {
                    consumer.accept(pack);
                }
            });
        }
    }
}